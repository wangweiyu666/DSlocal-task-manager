import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import { build } from "esbuild";

// Workers cannot compile schemas with new Function at runtime. Commit the
// standalone validator so cloud builds do not depend on installing the Web app.
const schema = JSON.parse(await readFile(new URL("../../docs/dst1-schema.json", import.meta.url), "utf8"));
const ajv = new Ajv2020({ allErrors: true, strict: false, validateFormats: false, code: { source: true, esm: true } });
const compiled = standaloneCode(ajv, ajv.compile(schema));
const result = await build({
  stdin: { contents: compiled, resolveDir: fileURLToPath(new URL("..", import.meta.url)) },
  bundle: true, write: false, format: "esm", platform: "browser", minify: true,
});
const notices = await Promise.all(["ajv", "fast-deep-equal"].map(async (name) => {
  const license = await readFile(new URL(`../node_modules/${name}/LICENSE`, import.meta.url), "utf8");
  return `${name}\n${license.replace(/\r\n/g, "\n").trim()}`;
}));
const generated = "// @ts-nocheck\n// Generated by web/scripts/generate-protocol-validator.mjs. Do not edit.\n/*!\n" + notices.join("\n\n") + "\n*/\n" + result.outputFiles[0].text;
const target = new URL("../../shared/protocol/schema-validator.ts", import.meta.url);
if (process.argv.includes("--check")) {
  if (await readFile(target, "utf8") !== generated) throw new Error("Run npm run generate:protocol in web to update the shared schema validator.");
} else {
  await writeFile(target, generated);
}
